#!/usr/bin/env python3
"""Wire the demo dashboard to real data, or restore the placeholder.

Usage, from repo root or demoUI/:
    python3 demoUI/wire_metrics.py ../runs/seq08_gt-labels   # real benchmark run
    python3 demoUI/wire_metrics.py --placeholder             # restore placeholder

Reads a benchmark run directory (results.json from the harness) and writes
demoUI/metrics.json AND demoUI/metrics.js (the file:// fallback - Chrome
blocks fetch() on file://, so the dashboard falls back to metrics.js setting
window.FOVEA_METRICS).

Fields the benchmark does not measure (fps, occupied_cells) are written as
null; the dashboard renders NOT MEASURED for them rather than inventing a
number. measured is set true only when reading a real run.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BANDS = ["0-10", "10-25", "25-50", "50-100"]

PLACEHOLDER = json.loads((HERE / "metrics.placeholder.json").read_text(encoding="utf-8")) \
    if (HERE / "metrics.placeholder.json").is_file() else None


def from_run(run_dir: Path) -> dict:
    results = json.loads((run_dir / "results.json").read_text(encoding="utf-8"))
    prov = results.get("provenance", {})
    hw = prov.get("hardware", {})

    def rep(name: str, label: str, resolution: str) -> dict:
        recall = results["recall"].get(name)
        return {
            "label": label,
            "resolution": resolution,
            "occupied_cells": None,          # not measured by the harness
            "memory_mb": results["memory_mb"].get(name),
            "fps": None,                     # measured only on the demo GPU (stage 5+)
            "recall_by_band": dict(zip(BANDS, recall)) if recall else None,
        }

    return {
        "measured": True,
        "provenance": {
            "git_commit": prov.get("git_commit"),
            "hardware": hw.get("platform"),
            "sequence": prov.get("dataset_split"),
            "inference": prov.get("inference_mode"),
            "timestamp": prov.get("timestamp_utc"),
        },
        "baseline": rep("voxel_5cm", "Uniform 5 cm 3D Voxel", "5 cm (uniform)"),
        "foveated": rep("foveated", "Foveated 2.5D Grid", "5 cm near → 40 cm far"),
    }


def write(metrics: dict) -> None:
    (HERE / "metrics.json").write_text(
        json.dumps(metrics, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
    (HERE / "metrics.js").write_text(
        "// Generated by wire_metrics.py - file:// fallback for metrics.json.\n"
        "// Do not edit by hand; edit metrics.json and re-run wire_metrics.py,\n"
        "// or re-wire from a benchmark run directory.\n"
        "window.FOVEA_METRICS = " + json.dumps(metrics, indent=2, ensure_ascii=True) + ";\n",
        encoding="utf-8")
    print(f"wrote metrics.json + metrics.js (measured={metrics['measured']})")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    if sys.argv[1] == "--placeholder":
        if PLACEHOLDER is None:
            print("metrics.placeholder.json missing", file=sys.stderr)
            return 1
        write(PLACEHOLDER)
        return 0
    run_dir = Path(sys.argv[1])
    if not (run_dir / "results.json").is_file():
        print(f"No results.json in {run_dir}", file=sys.stderr)
        return 1
    write(from_run(run_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
