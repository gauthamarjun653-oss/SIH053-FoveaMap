#!/usr/bin/env python3
"""Export ONE real KITTI scan as binned cells for the demo dashboard.

Usage, from the repo root (venv active):
    python3 demoUI/export_scene.py --seq 08 --frame 100

Reads the scan + SemanticKITTI ground-truth labels through the pipeline's own
modules (SequenceReader, raw->3-class map, ring table), bins the points into
(a) a uniform 5 cm 2D grid and (b) the foveated ring grid, and writes
demoUI/scene.json + demoUI/scene.js (the file:// fallback, same pattern as
metrics.js). The dashboard paints these cells directly, so the render IS the
binning - displayed cell counts are counted from the same lists that are
drawn.

Class mapping for the dashboard: ROAD -> 0 (terrain), STATIC -> 1,
DYNAMIC -> 2; IGNORE points are dropped. Cell class is the highest-severity
class present (matches the pipeline's render rule, AC-D4).
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from src.common.config import load_pipeline, load_rings          # noqa: E402
from src.io.kitti_reader import SequenceReader                   # noqa: E402
from src.segmentation.class_map import build_raw_to_class3       # noqa: E402

HERE = Path(__file__).resolve().parent
RANGE_MIN, RANGE_MAX = 2.5, 100.0
UNIFORM_CELL = 0.05


def bin_cells(x, y, cls, cell_size):
    """Highest-severity class per occupied cell. Returns flat [cx,cy,cls,...]."""
    cx = np.floor(x / cell_size).astype(np.int64)
    cy = np.floor(y / cell_size).astype(np.int64)
    order = np.lexsort((cls, cy, cx))          # class ascending within a cell
    cx_s, cy_s, cl_s = cx[order], cy[order], cls[order]
    new = np.empty(cx_s.shape[0], dtype=bool)
    new[0] = True
    new[1:] = (cx_s[1:] != cx_s[:-1]) | (cy_s[1:] != cy_s[:-1])
    starts = np.flatnonzero(new)
    ends = np.r_[starts[1:], cx_s.shape[0]]
    last = ends - 1                            # highest class = last in group
    flat = np.empty(starts.shape[0] * 3, dtype=np.int64)
    flat[0::3] = cx_s[starts]
    flat[1::3] = cy_s[starts]
    flat[2::3] = cl_s[last]
    return flat.tolist()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seq", default="08")
    ap.add_argument("--frame", type=int, default=100)
    args = ap.parse_args()

    cfg = load_pipeline(str(REPO / "configs" / "pipeline.yaml"))
    rings = load_rings(str(REPO / "configs" / "rings.yaml"))
    reader = SequenceReader(cfg.data_root, args.seq)
    raw_to_3 = build_raw_to_class3()

    pts = reader.scan(args.frame)
    labels3 = raw_to_3[reader.labels(args.frame)]      # 0=IGNORE 1=ROAD 2=STATIC 3=DYNAMIC

    x = pts[:, 0].astype(np.float64)
    y = pts[:, 1].astype(np.float64)
    r = np.hypot(x, y)
    keep = (r >= RANGE_MIN) & (r <= RANGE_MAX) & (labels3 > 0)
    x, y, r = x[keep], y[keep], r[keep]
    cls = (labels3[keep] - 1).astype(np.int64)          # dashboard: 0 terrain, 1 static, 2 dynamic

    uniform = bin_cells(x, y, cls, UNIFORM_CELL)
    fov_layers = []
    for ring in rings.rings:
        m = (r >= ring.radius_min) & (r <= ring.radius_max)
        cells = bin_cells(x[m], y[m], cls[m], ring.cell_size) if np.any(m) else []
        fov_layers.append({"cell": ring.cell_size, "cells": cells})

    n_dyn = int(np.count_nonzero(cls == 2))
    scene = {
        "source": "KITTI / SemanticKITTI ground-truth labels",
        "sequence": args.seq,
        "frame": args.frame,
        "points_used": int(x.shape[0]),
        "dynamic_points": n_dyn,
        "range_m": [RANGE_MIN, RANGE_MAX],
        "uniform": {"cell": UNIFORM_CELL, "cells": uniform},
        "foveated": fov_layers,
        "counts": {
            "uniform": len(uniform) // 3,
            "foveated": sum(len(l["cells"]) // 3 for l in fov_layers),
        },
    }
    (HERE / "scene.json").write_text(json.dumps(scene), encoding="utf-8")
    (HERE / "scene.js").write_text(
        "// Generated by export_scene.py - file:// fallback for scene.json.\n"
        "window.FOVEA_SCENE = " + json.dumps(scene) + ";\n", encoding="utf-8")
    print(f"seq {args.seq} frame {args.frame}: {scene['points_used']} points "
          f"({n_dyn} dynamic), uniform cells {scene['counts']['uniform']}, "
          f"foveated cells {scene['counts']['foveated']} "
          f"(ratio {scene['counts']['uniform'] / max(scene['counts']['foveated'], 1):.2f}x)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
